<?php

namespace App\Modules\RentCollection\Services;

use App\Modules\Invoices\Events\InvoiceSent;
use App\Modules\Invoices\Models\Invoice;
use App\Modules\Invoices\Services\InvoiceService;
use App\Modules\Leases\Models\Lease;
use Illuminate\Support\Carbon;

/**
 * Shared by two callers that need the same "does this lease need its
 * next rent invoice yet" logic: App\Modules\RentCollection\Console\
 * Commands\GenerateRentInvoices (the daily recurring sweep, respects
 * the lead-time window) and App\Modules\Leases\Services\LeaseService::
 * create() (needs the lease's FIRST invoice to exist immediately, not
 * whenever the lead-time window happens to open - a lease starting a
 * month out shouldn't leave the tenant with nothing to owe until days
 * before move-in).
 */
class RentInvoiceGenerator
{
    /**
     * How many days before the computed due date an invoice is
     * generated by the recurring sweep - matches the old hardcoded
     * "3 days before due" rhythm SendRentReminders used pre-
     * PaymentReminderRule.
     */
    public const LEAD_DAYS = 5;

    public function __construct(protected InvoiceService $invoiceService)
    {
    }

    /**
     * @param  bool  $ignoreLeadTime  true for a brand-new lease's first
     *  invoice (LeaseService::create()) - it should exist right away
     *  regardless of how far out start_date is, not wait for the
     *  recurring sweep's lead-time window to open.
     */
    public function generateNextInvoiceForLease(Lease $lease, bool $ignoreLeadTime = false): ?Invoice
    {
        $latestInvoice = $lease->invoices()->latest('due_date')->first();
        $nextDueDate = $latestInvoice
            ? $this->addBillingCycle($latestInvoice->due_date->copy(), $lease->billing_cycle)
            : $lease->start_date->copy();

        if (! $ignoreLeadTime && now()->lt($nextDueDate->copy()->subDays(self::LEAD_DAYS))) {
            return null;
        }

        if ($lease->end_date && $nextDueDate->gt($lease->end_date)) {
            return null;
        }

        $alreadyExists = $lease->invoices()->whereDate('due_date', $nextDueDate->toDateString())->exists();

        if ($alreadyExists) {
            return null;
        }

        $unit = $lease->unit;
        $unitLabel = $unit ? "Unit {$unit->unit_number}" : 'Unit';

        $invoice = $this->invoiceService->create([
            'company_id' => $lease->company_id,
            'lease_id' => $lease->id,
            'issue_date' => now()->toDateString(),
            'due_date' => $nextDueDate->toDateString(),
            'status' => 'sent',
            'items' => [[
                'description' => "Rent - {$unitLabel}, due {$nextDueDate->format('M j, Y')}",
                'quantity' => 1,
                'unit_price' => (float) $lease->rent_amount,
            ]],
        ]);

        InvoiceSent::dispatch($invoice);

        return $invoice;
    }

    protected function addBillingCycle(Carbon $date, string $cycle): Carbon
    {
        return match ($cycle) {
            'quarterly' => $date->addMonths(3),
            'semi_annual' => $date->addMonths(6),
            'annual' => $date->addYear(),
            default => $date->addMonth(),
        };
    }
}
